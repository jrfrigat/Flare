    /// <summary>The modifier class for a consumer kind key, such as <c>flare-gantt--kind-waiting</c>.</summary>
    public static string Kind(string? kind) => string.IsNullOrWhiteSpace(kind) ? "" : "flare-gantt--kind-" + Sanitize(kind);

    /// <summary>The modifier class for a link type, such as <c>flare-gantt__link--fs</c>.</summary>
    public static string LinkType(Components.Gantt.GanttLinkType type) => type switch
    {
        Components.Gantt.GanttLinkType.FinishToStart => "flare-gantt__link--fs",
        Components.Gantt.GanttLinkType.StartToStart => "flare-gantt__link--ss",
        Components.Gantt.GanttLinkType.FinishToFinish => "flare-gantt__link--ff",
        _ => "flare-gantt__link--sf"
    };

    private static string Sanitize(string kind)
    {
        Span<char> buffer = stackalloc char[kind.Length];
        for (var i = 0; i < kind.Length; i++)
            buffer[i] = char.IsLetterOrDigit(kind[i]) || kind[i] is '-' or '_' ? char.ToLowerInvariant(kind[i]) : '-';
        return new string(buffer);
    }
