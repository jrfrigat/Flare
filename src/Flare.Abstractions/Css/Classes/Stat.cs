namespace Flare.Css.Classes;

/// <summary>CSS classes for the stat (one labelled metric: value, unit, icon, change, caption).</summary>
public static class Stat
{
    /// <summary>The <c>flare-stat</c> CSS class.</summary>
    public const string Root = "flare-stat";
    /// <summary>The <c>flare-stat--sm</c> CSS class (smaller value type).</summary>
    public const string SizeSm = "flare-stat--sm";
    /// <summary>The <c>flare-stat--md</c> CSS class (the default value type).</summary>
    public const string SizeMd = "flare-stat--md";
    /// <summary>The <c>flare-stat--lg</c> CSS class (larger value type).</summary>
    public const string SizeLg = "flare-stat--lg";
    /// <summary>The <c>flare-stat__icon</c> CSS class (the tonal square holding the icon).</summary>
    public const string Icon = "flare-stat__icon";
    /// <summary>The <c>flare-stat__body</c> CSS class (label, value row and caption).</summary>
    public const string Body = "flare-stat__body";
    /// <summary>The <c>flare-stat__label</c> CSS class.</summary>
    public const string Label = "flare-stat__label";
    /// <summary>The <c>flare-stat__value-row</c> CSS class (value, unit and change on one baseline).</summary>
    public const string ValueRow = "flare-stat__value-row";
    /// <summary>The <c>flare-stat__value</c> CSS class.</summary>
    public const string Value = "flare-stat__value";
    /// <summary>The <c>flare-stat__unit</c> CSS class.</summary>
    public const string Unit = "flare-stat__unit";
    /// <summary>The <c>flare-stat__delta</c> CSS class (the change, colored by its role).</summary>
    public const string Delta = "flare-stat__delta";
    /// <summary>The <c>flare-stat__caption</c> CSS class.</summary>
    public const string Caption = "flare-stat__caption";
}
