namespace Flare.Css.Classes;

/// <summary>CSS classes for the split pane.</summary>
public static class SplitPane
{
    /// <summary>The <c>flare-split-pane</c> CSS class.</summary>
    public const string Root = "flare-split-pane";
    /// <summary>The <c>flare-split-pane--horizontal</c> CSS class: panes side by side.</summary>
    public const string Horizontal = "flare-split-pane--horizontal";
    /// <summary>The <c>flare-split-pane--vertical</c> CSS class: panes stacked.</summary>
    public const string Vertical = "flare-split-pane--vertical";
    /// <summary>The <c>flare-split-pane__first</c> CSS class: the pane sized by the fraction.</summary>
    public const string First = "flare-split-pane__first";
    /// <summary>The <c>flare-split-pane__second</c> CSS class: the pane that fills the rest.</summary>
    public const string Second = "flare-split-pane__second";
}
