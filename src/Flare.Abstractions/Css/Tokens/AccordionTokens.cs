namespace Flare.Css.Tokens;

/// <summary>CSS variable tokens for the accordion container, its panel headers and their bodies.</summary>
public static class AccordionField
{
    /// <summary>CSS custom-property name for the accordion container border token.</summary>
    public const string Border = "--flare-accordion-border";
    /// <summary>CSS custom-property name for the accordion container corner radius token.</summary>
    public const string Radius = "--flare-accordion-radius";
    /// <summary>CSS custom-property name for the rule drawn between adjacent panels token.</summary>
    public const string PanelDivider = "--flare-accordion-panel-divider";
    /// <summary>CSS custom-property name for the panel header background token.</summary>
    public const string HeaderBg = "--flare-accordion-header-bg";
    /// <summary>CSS custom-property name for the panel header foreground token.</summary>
    public const string HeaderColor = "--flare-accordion-header-color";
    /// <summary>CSS custom-property name for the panel header block padding token.</summary>
    public const string HeaderPaddingBlock = "--flare-accordion-header-padding-block";
    /// <summary>CSS custom-property name for the panel header inline padding token.</summary>
    public const string HeaderPaddingInline = "--flare-accordion-header-padding-inline";
    /// <summary>CSS custom-property name for the gap between a header's inline content token.</summary>
    public const string HeaderGap = "--flare-accordion-header-gap";
    /// <summary>CSS custom-property name for the panel header font family token.</summary>
    public const string HeaderLabelFont = "--flare-accordion-header-label-font";
    /// <summary>CSS custom-property name for the panel header font size token.</summary>
    public const string HeaderLabelSize = "--flare-accordion-header-label-size";
    /// <summary>CSS custom-property name for the panel header font weight token.</summary>
    public const string HeaderLabelWeight = "--flare-accordion-header-label-weight";
    /// <summary>CSS custom-property name for the disabled panel header opacity token.</summary>
    public const string HeaderDisabledOpacity = "--flare-accordion-header-disabled-opacity";
    /// <summary>CSS custom-property name for the expand/collapse chevron size token.</summary>
    public const string IconSize = "--flare-accordion-icon-size";
    /// <summary>CSS custom-property name for the panel body block padding token.</summary>
    public const string BodyPaddingBlock = "--flare-accordion-body-padding-block";
    /// <summary>CSS custom-property name for the panel body inline padding token.</summary>
    public const string BodyPaddingInline = "--flare-accordion-body-padding-inline";
    /// <summary>CSS custom-property name for the panel body foreground token.</summary>
    public const string BodyColor = "--flare-accordion-body-color";
}
