namespace Flare.Css.Tokens;

/// <summary>CSS variable tokens for the title-bar caption control.</summary>
public static class CaptionButton
{
    /// <summary>CSS custom-property name for the control width.</summary>
    public const string Width = "--flare-caption-width";
    /// <summary>CSS custom-property name for the control height.</summary>
    public const string Height = "--flare-caption-height";
    /// <summary>CSS custom-property name for the drawn glyph size.</summary>
    public const string GlyphSize = "--flare-caption-glyph-size";
    /// <summary>CSS custom-property name for the control corner radius.</summary>
    public const string Radius = "--flare-caption-radius";
    /// <summary>CSS custom-property name for the resting background.</summary>
    public const string Background = "--flare-caption-bg";
    /// <summary>CSS custom-property name for the resting glyph color.</summary>
    public const string Color = "--flare-caption-color";
    /// <summary>CSS custom-property name for the hover background.</summary>
    public const string HoverBackground = "--flare-caption-hover-bg";
    /// <summary>CSS custom-property name for the hover glyph color.</summary>
    public const string HoverColor = "--flare-caption-hover-color";
    /// <summary>CSS custom-property name for the pressed background.</summary>
    public const string PressedBackground = "--flare-caption-pressed-bg";
    /// <summary>CSS custom-property name for the pressed glyph color.</summary>
    public const string PressedColor = "--flare-caption-pressed-color";
    /// <summary>CSS custom-property name for the keyboard focus outline.</summary>
    public const string FocusOutline = "--flare-caption-focus-outline";
    /// <summary>CSS custom-property name for the distance the focus outline sits from the control edge.</summary>
    public const string FocusOffset = "--flare-caption-focus-offset";
    /// <summary>CSS custom-property name for the disabled control opacity.</summary>
    public const string DisabledOpacity = "--flare-caption-disabled-opacity";
    /// <summary>CSS custom-property name for the close control's hover background.</summary>
    public const string CloseHoverBackground = "--flare-caption-close-hover-bg";
    /// <summary>CSS custom-property name for the close control's hover glyph color.</summary>
    public const string CloseHoverColor = "--flare-caption-close-hover-color";
    /// <summary>CSS custom-property name for the close control's pressed background.</summary>
    public const string ClosePressedBackground = "--flare-caption-close-pressed-bg";
    /// <summary>CSS custom-property name for the close control's pressed glyph color.</summary>
    public const string ClosePressedColor = "--flare-caption-close-pressed-color";
}
