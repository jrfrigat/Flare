namespace Flare.Css.Tokens;

/// <summary>CSS variable tokens for file upload.</summary>
public static class FileUploadField
{
    /// <summary>CSS custom-property name for the drop zone's dashed border width.</summary>
    public const string BorderWidth = "--flare-file-upload-border-width";
    /// <summary>CSS custom-property name for the drop zone's hover background.</summary>
    public const string HoverBg = "--flare-file-upload-hover-bg";
    /// <summary>CSS custom-property name for the drop zone's background while a file is dragged over it.</summary>
    public const string DraggingBg = "--flare-file-upload-dragging-bg";
    /// <summary>CSS custom-property name for the inset ring drawn while a file is dragged over the zone.</summary>
    public const string DraggingRingWidth = "--flare-file-upload-dragging-ring-width";
    /// <summary>CSS custom-property name for the drop zone's large upload glyph.</summary>
    public const string IconSize = "--flare-file-upload-icon-size";
    /// <summary>CSS custom-property name for the drop zone's resting height.</summary>
    public const string ZoneMinHeight = "--flare-file-upload-zone-min-height";
    /// <summary>CSS custom-property name for the drop zone's corner radius.</summary>
    public const string ZoneRadius = "--flare-file-upload-zone-radius";
    /// <summary>CSS custom-property name for the per-file glyph in the selected-files list.</summary>
    public const string FileIconSize = "--flare-file-upload-file-icon-size";
    /// <summary>CSS custom-property name for the gap between the file rows.</summary>
    public const string RowGap = "--flare-file-upload-row-gap";
    /// <summary>CSS custom-property name for the corner radius of one file row.</summary>
    public const string RowRadius = "--flare-file-upload-row-radius";
    /// <summary>CSS custom-property name for the background of a row whose transfer is running.</summary>
    public const string RowActiveBg = "--flare-file-upload-row-active-bg";
    /// <summary>CSS custom-property name for the background of a completed row.</summary>
    public const string RowSuccessBg = "--flare-file-upload-row-success-bg";
    /// <summary>CSS custom-property name for the background of a failed or cancelled row.</summary>
    public const string RowErrorBg = "--flare-file-upload-row-error-bg";
    /// <summary>CSS custom-property name for the foreground of the message on a failed row.</summary>
    public const string RowErrorColor = "--flare-file-upload-row-error-color";
}
