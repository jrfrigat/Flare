namespace Flare.Css.Tokens;

/// <summary>CSS variable tokens for checkbox.</summary>
public static class Checkbox
{
    /// <summary>CSS custom-property name for the extra-small box size token.</summary>
    public const string SizeXs = "--flare-checkbox-size-xs";
    /// <summary>CSS custom-property name for the small box size token.</summary>
    public const string SizeSm = "--flare-checkbox-size-sm";
    /// <summary>CSS custom-property name for the medium (default) box size token.</summary>
    public const string SizeMd = "--flare-checkbox-size-md";
    /// <summary>CSS custom-property name for the large box size token.</summary>
    public const string SizeLg = "--flare-checkbox-size-lg";
    /// <summary>CSS custom-property name for the extra-large box size token.</summary>
    public const string SizeXl = "--flare-checkbox-size-xl";
    /// <summary>CSS custom-property name for the diameter of the state-layer halo. The halo is centred
    /// on the box at every step, so one diameter covers the whole ramp.</summary>
    public const string StateLayerSize = "--flare-checkbox-state-layer-size";
    /// <summary>CSS custom-property name for the border width token.</summary>
    public const string BorderWidth = "--flare-checkbox-border-width";
    /// <summary>CSS custom-property name for the radius token.</summary>
    public const string Radius = "--flare-checkbox-radius";
    /// <summary>CSS custom-property name for the state layer hover token.</summary>
    public const string StateLayerHover = "--flare-checkbox-state-layer-hover";
    /// <summary>CSS custom-property name for the state layer hover checked token.</summary>
    public const string StateLayerHoverChecked = "--flare-checkbox-state-layer-hover-checked";
    /// <summary>CSS custom-property name for the focus outline token.</summary>
    public const string FocusOutline = "--flare-checkbox-focus-outline";
    /// <summary>CSS custom-property name for the focus outline offset token.</summary>
    public const string FocusOutlineOffset = "--flare-checkbox-focus-outline-offset";
    /// <summary>CSS custom-property name for the focus shadow token.</summary>
    public const string FocusShadow = "--flare-checkbox-focus-shadow";
    /// <summary>CSS custom-property name for the disabled opacity token.</summary>
    public const string DisabledOpacity = "--flare-checkbox-disabled-opacity";
}

