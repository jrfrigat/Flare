namespace Flare.Css.Tokens;

/// <summary>CSS variable tokens for scroll.</summary>
public static class ScrollTopField
{
    /// <summary>CSS custom-property name for the top inset token.</summary>
    public const string TopInset = "--flare-scroll-top-inset";
    /// <summary>CSS custom-property name for the top size token.</summary>
    public const string TopSize = "--flare-scroll-top-size";
    /// <summary>CSS custom-property name for the height of an app's own bottom bar, added under the
    /// button so it never covers that bar's actions.</summary>
    public const string PanelOffset = "--flare-scroll-top-panel-offset";
}
